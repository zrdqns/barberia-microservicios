-- Tablas de api-citas. Se ejecuta en cada arranque y solo crea lo que falta.

CREATE SCHEMA IF NOT EXISTS citas;

CREATE TABLE IF NOT EXISTS citas.cliente (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(100) NOT NULL,
    documento VARCHAR(10)  NOT NULL UNIQUE,
    telefono  VARCHAR(10)  NOT NULL,
    correo    VARCHAR(255)
);

-- Horario de atención de la barbería, un registro por día de la semana (1 = lunes, 7 = domingo).
-- Un día sin apertura ni cierre es un día en que no se atiende.
CREATE TABLE IF NOT EXISTS citas.horario (
    dia_semana INTEGER PRIMARY KEY CHECK (dia_semana BETWEEN 1 AND 7),
    apertura   TIME,
    cierre     TIME,
    CHECK ((apertura IS NULL AND cierre IS NULL) OR apertura < cierre)
);

CREATE TABLE IF NOT EXISTS citas.cita (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora       TIMESTAMP    NOT NULL,
    estado           VARCHAR(12)  NOT NULL CHECK (estado IN ('PROGRAMADA', 'COMPLETADA', 'CANCELADA')),
    observaciones    VARCHAR(500),
    -- Si se elimina el cliente, sus citas anteriores quedan con el nombre que tenía
    cliente_id       INTEGER      REFERENCES citas.cliente (id) ON DELETE SET NULL,
    cliente_nombre   VARCHAR(100) NOT NULL,
    -- El servicio y el barbero viven en api-catalogo, en otro esquema, así que no hay llave
    -- foránea: la cita guarda sus IDs y lo que valían al agendarla.
    servicio_id      INTEGER      NOT NULL,
    servicio_nombre  VARCHAR(100) NOT NULL,
    precio           INTEGER      NOT NULL CHECK (precio > 0),
    duracion_minutos INTEGER      NOT NULL CHECK (duracion_minutos > 0),
    barbero_id       INTEGER      NOT NULL,
    barbero_nombre   VARCHAR(100) NOT NULL
);

-- Al agendar se buscan las citas que se cruzan por fecha
CREATE INDEX IF NOT EXISTS cita_fecha_hora ON citas.cita (fecha_hora);
