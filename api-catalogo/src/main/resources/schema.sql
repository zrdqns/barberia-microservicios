-- Tablas de api-catalogo. Se ejecuta en cada arranque y solo crea lo que falta.

CREATE SCHEMA IF NOT EXISTS catalogo;

CREATE TABLE IF NOT EXISTS catalogo.servicio (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(100) NOT NULL UNIQUE,
    descripcion      VARCHAR(255),
    -- Pesos colombianos, sin decimales
    precio           INTEGER      NOT NULL CHECK (precio > 0),
    duracion_minutos INTEGER      NOT NULL CHECK (duracion_minutos BETWEEN 5 AND 240),
    activo           BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS catalogo.barbero (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(100) NOT NULL,
    documento    VARCHAR(10)  NOT NULL UNIQUE,
    telefono     VARCHAR(10),
    especialidad VARCHAR(255),
    activo       BOOLEAN      NOT NULL DEFAULT TRUE
);
